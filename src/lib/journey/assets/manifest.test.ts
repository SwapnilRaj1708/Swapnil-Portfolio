// @vitest-environment node
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { isMeshName, materialKind } from "./contract-rules";
import { ASSET_MANIFEST, assetUrl, findAsset, variantForTier } from "./manifest";

// PF-009: the generated manifest, the files it names (committed in public/assets/), and the
// tier → file rule.

const PUBLIC = path.resolve(__dirname, "../../../../public");

describe("tier → variant", () => {
  it("high and medium load -high, low loads -low, static and pending nothing", () => {
    expect(variantForTier("high")).toBe("high");
    expect(variantForTier("medium")).toBe("high");
    expect(variantForTier("low")).toBe("low");
    expect(variantForTier("static")).toBeNull();
    expect(variantForTier("pending")).toBeNull();
  });
});

describe("the manifest (generated by npm run asset)", () => {
  it("holds the contract test piece", () => {
    const entry = findAsset("shared/pipeline-test");
    expect(entry).not.toBeNull();
    expect(entry).toMatchObject({
      chapter: "shared",
      slug: "pipeline-test",
      source: { file: "shared/export/pipeline-test.glb", bytes: 348_588 },
      licence: "owner, all rights reserved",
      triangles: 982,
      trianglesDrawn: 1120,
      objects: 13,
      clips: [{ name: "shared_test_cube_rise" }],
      instances: [{ prop: "pin", source: "shared_pin", count: 4 }],
    });
    expect(entry!.materials.map((m) => m.name)).toEqual(["BAKED_pipeline_bench", "GLOW_trace_amber", "PBR_test_metal", "SHADER_test_grid"]);
    expect(entry!.textures.map((t) => [t.name, t.colorSpace, t.high.width, t.low.width])).toEqual([
      ["BAKED_pipeline_bench", "srgb", 1024, 512],
      ["PBR_test_metal_normal", "linear", 512, 256],
    ]);
    expect(assetUrl(entry!, "low")).toBe("/assets/shared/pipeline-test/pipeline-test-low.glb");
  });

  it.each(ASSET_MANIFEST.map((e) => [e.key, e]))("%s: its files exist with the recorded size and SHA-256", (_key, entry) => {
    for (const variant of ["high", "low"] as const) {
      const file = path.join(PUBLIC, "assets", entry.chapter, entry.slug, entry.files[variant].file);
      expect(existsSync(file)).toBe(true);
      const bytes = readFileSync(file);
      expect(bytes.byteLength).toBe(entry.files[variant].bytes);
      expect(createHash("sha256").update(bytes).digest("hex")).toBe(entry.files[variant].sha256);
    }
    expect(readdirSync(path.join(PUBLIC, "assets", entry.chapter, entry.slug)).sort()).toEqual([entry.files.high.file, entry.files.low.file].sort());
  });

  it.each(ASSET_MANIFEST.map((e) => [e.key, e]))("%s: names follow the contract", (_key, entry) => {
    for (const m of entry.materials) expect(materialKind(m.name)).toBe(m.kind);
    for (const i of entry.instances) expect(isMeshName(i.source, entry.chapter)).toBe(true);
    expect(entry.date).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });
});
