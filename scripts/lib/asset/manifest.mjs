// The asset manifest: a generated, typed module the site imports
// (src/lib/journey/assets/manifest.generated.ts) and the table in docs/assets.md between markers.
// Both are rewritten from the full list of entries on every pipeline run, sorted by key, so the
// same entries always give the same bytes.

export const MANIFEST_START = "// <asset-manifest>";
export const MANIFEST_END = "// </asset-manifest>";
export const DOCS_START = "<!-- asset-manifest:start – generated by `npm run asset`, do not edit by hand -->";
export const DOCS_END = "<!-- asset-manifest:end -->";

/** The entries in a generated manifest file's text ([] for none). */
export function parseManifest(text) {
  const start = text.indexOf(MANIFEST_START);
  const end = text.indexOf(MANIFEST_END);
  if (start < 0 || end < start) throw new Error("manifest.generated.ts: the <asset-manifest> markers are missing");
  const block = text.slice(start + MANIFEST_START.length, end);
  const assign = block.indexOf("= ");
  const open = assign < 0 ? -1 : block.indexOf("[", assign);
  const close = block.lastIndexOf("]");
  if (open < 0 || close < open) throw new Error("manifest.generated.ts: no entry list between the markers");
  return JSON.parse(block.slice(open, close + 1));
}

export function renderManifest(entries) {
  const sorted = [...entries].sort((a, b) => a.key.localeCompare(b.key));
  return [
    "// GENERATED by the asset pipeline (`npm run asset -- <chapter>/<slug>`, scripts/asset.mjs).",
    "// Do not edit by hand: the next pipeline run rewrites this file from its own records.",
    'import type { AssetManifestEntry } from "./manifest-types";',
    "",
    MANIFEST_START,
    `export const ASSET_MANIFEST: readonly AssetManifestEntry[] = ${JSON.stringify(sorted, null, 2)};`,
    MANIFEST_END,
    "",
  ].join("\n");
}

const group = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
const bytes = (n) => `${group(n)} B`;

function texturesCell(entry) {
  if (!entry.textures.length) return "none";
  return entry.textures
    .map((t) => `${t.name} ${t.high.width}² → ${t.low.width}² ${t.colorSpace === "srgb" ? "sRGB" : "linear"} ${t.codec.toUpperCase()}`)
    .join("; ");
}

function candidatesCell(t, codec) {
  const c = t.candidates?.find((x) => x.codec === codec);
  return c ? `${bytes(c.bytes)} · SSIM ${c.ssim.toFixed(4)} · ${c.psnr.toFixed(1)} dB` : "–";
}

/** The generated part of docs/assets.md. */
export function renderDocsTable(entries) {
  const sorted = [...entries].sort((a, b) => a.key.localeCompare(b.key));
  const rows = sorted.map(
    (e) =>
      `| \`${e.slug}\` | ${e.chapter} | \`${e.source.file}\` (${bytes(e.source.bytes)}) | ${e.date} | ${group(e.triangles)} (${group(e.trianglesDrawn)} drawn) | ` +
      `${texturesCell(e)} | ${bytes(e.files.high.bytes)} | ${bytes(e.files.low.bytes)} | ${e.licence} |`,
  );
  const textureRows = sorted.flatMap((e) =>
    e.textures.map(
      (t) =>
        `| \`${e.slug}\` | ${t.name} | ${t.slots.join(", ")} | ${t.colorSpace === "srgb" ? "sRGB" : "linear"} | ${candidatesCell(t, "etc1s")} | ` +
        `${candidatesCell(t, "uastc")} | **${t.codec.toUpperCase()}** | ${bytes(t.high.bytes)} / ${bytes(t.low.bytes)} |`,
    ),
  );
  const lines = [
    DOCS_START,
    "| Slug | Chapter | Source file | Date | Triangles | Textures (high → low) | Size high | Size low | Licence |",
    "|---|---|---|---|---|---|---|---|---|",
    ...rows,
  ];
  if (textureRows.length) {
    lines.push(
      "",
      "Texture encodings (KTX2, measured on the high variant by `ktx create --compare-ssim --compare-psnr`, level 0, lowest channel SSIM; a colour image is kept as ETC1S only at SSIM ≥ 0.995, `scripts/lib/asset/settings.mjs`):",
      "",
      "| Slug | Texture | Slots | Colour space | ETC1S (bytes · SSIM · PSNR) | UASTC (bytes · SSIM · PSNR) | Chosen | Bytes high / low |",
      "|---|---|---|---|---|---|---|---|",
      ...textureRows,
    );
  }
  lines.push(DOCS_END);
  return lines.join("\n");
}

/** docs/assets.md with its generated part replaced. */
export function updateDocs(text, table) {
  const start = text.indexOf(DOCS_START);
  const end = text.indexOf(DOCS_END);
  if (start < 0 || end < start) throw new Error("docs/assets.md: the asset-manifest markers are missing");
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  return text.slice(0, start) + table.replaceAll("\n", eol) + text.slice(end + DOCS_END.length);
}
